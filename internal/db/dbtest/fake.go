// Describe implements db.Conn.
func (f *FakeConn) Describe(ctx context.Context, ref db.RelationRef) (db.RelationDetail, error) {
	f.mu.Lock()
	defer f.mu.Unlock()
	f.recordLocked("Describe " + ref.String())
	if err := f.checkLocked(ctx); err != nil {
		return db.RelationDetail{}, err
	}
	detail, ok := f.details[ref]
	if !ok {
		return db.RelationDetail{}, fmt.Errorf("dbtest: unknown relation %s", ref)
	}
	return detail, nil
}

// Page implements db.Conn. It generates deterministic rows from the relation's
// configured total and records the requested ordering.
func (f *FakeConn) Page(ctx context.Context, ref db.RelationRef, order []db.Order, limit, offset int) (*db.Result, error) {
	f.mu.Lock()
	defer f.mu.Unlock()

	f.recordLocked(fmt.Sprintf(
		"Page %s limit=%d offset=%d order=%s",
		ref, limit, offset, formatOrder(order),
	))
	if err := f.checkLocked(ctx); err != nil {
		return nil, err
	}
	if limit <= 0 {
		return nil, errors.New("dbtest: limit must be positive")
	}
	if offset < 0 {
		return nil, errors.New("dbtest: offset must be non-negative")
	}

	detail, ok := f.details[ref]
	if !ok {
		return nil, fmt.Errorf("dbtest: unknown relation %s", ref)
	}

	total := f.totalForLocked(ref)
	end := min(offset+limit, total)
	if offset > total {
		offset = total
	}

	rows := make([][]db.Cell, 0, max(end-offset, 0))
	for row := offset; row < end; row++ {
		cells := make([]db.Cell, len(detail.Columns))
		for i, column := range detail.Columns {
			cells[i] = fakeCell(column, row)
		}
		rows = append(rows, cells)
	}

	return &db.Result{
		Columns:   resultColumns(detail.Columns),
		Rows:      rows,
		RowCount:  len(rows),
		Truncated: end < total,
		Statement: "fake page: " + ref.String(),
	}, nil
}

// Count implements db.Conn.
func (f *FakeConn) Count(ctx context.Context, ref db.RelationRef) (db.Count, error) {
	f.mu.Lock()
	defer f.mu.Unlock()
	f.recordLocked("Count " + ref.String())
	if err := f.checkLocked(ctx); err != nil {
		return db.Count{}, err
	}
	return f.counts[ref], nil
}

// Query implements db.Conn. Results are matched by exact statement text and
// capped at maxRows.
func (f *FakeConn) Query(ctx context.Context, sql string, maxRows int) (*db.Result, error) {
	f.mu.Lock()
	defer f.mu.Unlock()
	f.recordLocked("Query " + sql)
	if err := f.checkLocked(ctx); err != nil {
		return nil, err
	}
	if maxRows <= 0 {
		maxRows = db.DefaultMaxRows
	}

	result, ok := f.queryResults[sql]
	if !ok {
		result = f.defaultResult
	}
	result.Columns = slices.Clone(result.Columns)
	result.Rows = slices.Clone(result.Rows)
	result.Statement = sql
	if len(result.Rows) > maxRows {
		result.Rows = result.Rows[:maxRows]
		result.Truncated = true
	}
	result.RowCount = len(result.Rows)
	return &result, nil
}

// Quote implements db.Conn.
func (f *FakeConn) Quote(parts ...string) string {
	quoted := make([]string, len(parts))
	for i, part := range parts {
		quoted[i] = `"` + strings.ReplaceAll(part, `"`, `""`) + `"`
	}
	return strings.Join(quoted, ".")
}

// Close implements db.Conn. It is idempotent.
func (f *FakeConn) Close() error {
	f.mu.Lock()
	defer f.mu.Unlock()
	f.recordLocked("Close")
	f.closed = true
	return nil
}

func (f *FakeConn) recordLocked(call string) {
	f.calls = append(f.calls, call)
}

func (f *FakeConn) checkLocked(ctx context.Context) error {
	if err := ctx.Err(); err != nil {
		return err
	}
	if f.closed {
		return ErrClosed
	}
	return f.err
}

func (f *FakeConn) totalForLocked(ref db.RelationRef) int {
	if total, ok := f.totals[ref]; ok {
		return total
	}
	if count, ok := f.counts[ref]; ok && count.Exact && count.Value > 0 {
		return int(count.Value)
	}
	return 0
}

func resultColumns(columns []db.Column) []db.ResultColumn {
	result := make([]db.ResultColumn, len(columns))
	for i, column := range columns {
		result[i] = db.ResultColumn{
			Name:         column.Name,
			DatabaseType: column.DataType,
			Nullable:     column.Nullable,
		}
	}
	return result
}

func fakeCell(column db.Column, row int) db.Cell {
	switch column.Name {
	case "id", "user_id":
		return db.Cell{Text: strconv.Itoa(row + 1)}
	case "email":
		if row%7 == 3 {
			return db.Cell{Null: true}
		}
		return db.Cell{Text: fmt.Sprintf("user%d@example.com", row+1)}
	case "created_at":
		return db.Cell{Text: fakeEpoch.Add(time.Duration(row) * time.Hour).Format(time.RFC3339)}
	case "total":
		return db.Cell{Text: fmt.Sprintf("%d.00", row%100+1)}
	default:
		return db.Cell{Text: fmt.Sprintf("%s-%d", column.Name, row+1)}
	}
}

func formatOrder(order []db.Order) string {
	if len(order) == 0 {
		return "-"
	}
	parts := make([]string, len(order))
	for i, item := range order {
		direction := "asc"
		if item.Desc {
			direction = "desc"
		}
		parts[i] = item.Column + ":" + direction
	}
	return strings.Join(parts, ",")
}

// FakeConnector is a deterministic db.Connector for connection-picker tests.
type FakeConnector struct {
	mu sync.Mutex

	kind        db.Kind
	conn        db.Conn
	err         error
	opens       int
	lastDSN     string
	lastOptions db.Options
}

// NewFakeConnector returns a connector backed by NewFakeConn.
func NewFakeConnector() *FakeConnector {
	conn := NewFakeConn()
	return &FakeConnector{kind: conn.Kind(), conn: conn}
}

// Kind implements db.Connector.
func (c *FakeConnector) Kind() db.Kind {
	c.mu.Lock()
	defer c.mu.Unlock()
	return c.kind
}

// Open implements db.Connector and records the request.
func (c *FakeConnector) Open(ctx context.Context, dsn string, opts db.Options) (db.Conn, error) {
	c.mu.Lock()
	defer c.mu.Unlock()
	c.opens++
	c.lastDSN = dsn
	c.lastOptions = opts

	if err := ctx.Err(); err != nil {
		return nil, err
	}
	if c.err != nil {
		return nil, c.err
	}
	if c.conn == nil {
		return nil, errors.New("dbtest: fake connector has no connection")
	}
	return c.conn, nil
}

// SetKind changes the connector's reported kind.
func (c *FakeConnector) SetKind(kind db.Kind) {
	c.mu.Lock()
	defer c.mu.Unlock()
	c.kind = kind
}

// SetConn changes the connection returned by Open.
func (c *FakeConnector) SetConn(conn db.Conn) {
	c.mu.Lock()
	defer c.mu.Unlock()
	c.conn = conn
}

// SetError makes Open fail with err. Passing nil clears it.
func (c *FakeConnector) SetError(err error) {
	c.mu.Lock()
	defer c.mu.Unlock()
	c.err = err
}

// OpenCount returns the number of Open calls.
func (c *FakeConnector) OpenCount() int {
	c.mu.Lock()
	defer c.mu.Unlock()
	return c.opens
}

// LastOpen returns the most recent Open request.
func (c *FakeConnector) LastOpen() (string, db.Options, bool) {
	c.mu.Lock()
	defer c.mu.Unlock()
	return c.lastDSN, c.lastOptions, c.opens > 0
}

var (
	_ db.Conn      = (*FakeConn)(nil)
	_ db.Connector = (*FakeConnector)(nil)
)
