// ErrClosed is returned when a fake connection is used after Close.
var ErrClosed = errors.New("dbtest: fake connection closed")

var fakeEpoch = time.Date(2026, time.January, 1, 0, 0, 0, 0, time.UTC)

// FakeConn is a deterministic, concurrency-safe implementation of db.Conn.
type FakeConn struct {
	mu sync.Mutex

	kind    db.Kind
	version string
	schemas []db.Schema

	relations map[string][]db.Relation
	details   map[db.RelationRef]db.RelationDetail
	counts    map[db.RelationRef]db.Count
	totals    map[db.RelationRef]int

	queryResults  map[string]db.Result
	defaultResult db.Result

	err    error
	closed bool
	calls  []string
}

// NewFakeConn returns a fake connection with a small deterministic catalog.
func NewFakeConn() *FakeConn {
	users := db.Relation{Schema: "public", Name: "users", Kind: db.RelationTable}
	orders := db.Relation{Schema: "public", Name: "orders", Kind: db.RelationView}
	usersRef := users.Ref()
	ordersRef := orders.Ref()

	return &FakeConn{
		kind:    db.KindPostgres,
		version: "16.0 (fake)",
		schemas: []db.Schema{{Name: "public"}},
		relations: map[string][]db.Relation{
			"public": {users, orders},
		},
		details: map[db.RelationRef]db.RelationDetail{
			usersRef: {
				Relation: users,
				Columns: []db.Column{
					{Name: "id", DataType: "bigint", Position: 1, IsPrimaryKey: true},
					{Name: "email", DataType: "text", Nullable: true, Position: 2},
					{Name: "created_at", DataType: "timestamp with time zone", Position: 3},
				},
				Indexes: []db.Index{
					{Name: "users_pkey", Columns: []string{"id"}, Unique: true, Primary: true, Method: "btree"},
				},
				DDL:          "CREATE TABLE public.users (id bigint PRIMARY KEY, email text, created_at timestamptz NOT NULL)",
				DDLSupported: true,
			},
			ordersRef: {
				Relation: orders,
				Columns: []db.Column{
					{Name: "id", DataType: "bigint", Position: 1, IsPrimaryKey: true},
					{Name: "user_id", DataType: "bigint", Position: 2},
					{Name: "total", DataType: "numeric(12,2)", Position: 3},
					{Name: "created_at", DataType: "timestamp with time zone", Nullable: true, Position: 4},
				},
				Indexes: []db.Index{
					{Name: "orders_pkey", Columns: []string{"id"}, Unique: true, Primary: true, Method: "btree"},
				},
				ForeignKeys: []db.ForeignKey{
					{
						Name:       "orders_user_id_fkey",
						Columns:    []string{"user_id"},
						RefSchema:  "public",
						RefTable:   "users",
						RefColumns: []string{"id"},
						OnDelete:   "CASCADE",
						OnUpdate:   "NO ACTION",
					},
				},
			},
		},
		counts: map[db.RelationRef]db.Count{
			usersRef:  {Value: 250, Exact: true},
			ordersRef: {Value: 12, Exact: true},
		},
		totals: map[db.RelationRef]int{
			usersRef:  250,
			ordersRef: 12,
		},
		queryResults: make(map[string]db.Result),
		defaultResult: db.Result{
			Columns:  []db.ResultColumn{{Name: "result", DatabaseType: "text"}},
			Rows:     [][]db.Cell{{{Text: "ok"}}},
			RowCount: 1,
		},
	}
}

// Kind returns the fake connection's database kind.
func (f *FakeConn) Kind() db.Kind {
	return f.kind
}

// SetError makes subsequent operations fail with err. Passing nil clears it.
func (f *FakeConn) SetError(err error) {
	f.mu.Lock()
	defer f.mu.Unlock()
	f.err = err
}

// SetQueryResult configures the result returned for an exact SQL statement.
func (f *FakeConn) SetQueryResult(sql string, result db.Result) {
	f.mu.Lock()
	defer f.mu.Unlock()
	result.Columns = slices.Clone(result.Columns)
	result.Rows = slices.Clone(result.Rows)
	f.queryResults[sql] = result
}

// SetCount overrides a relation's count.
func (f *FakeConn) SetCount(ref db.RelationRef, count db.Count) {
	f.mu.Lock()
	defer f.mu.Unlock()
	f.counts[ref] = count
}

// SetTotal overrides the number of rows generated by Page.
func (f *FakeConn) SetTotal(ref db.RelationRef, total int) {
	f.mu.Lock()
	defer f.mu.Unlock()
	f.totals[ref] = total
}

// Calls returns a copy of the recorded operation log.
func (f *FakeConn) Calls() []string {
	f.mu.Lock()
	defer f.mu.Unlock()
	return slices.Clone(f.calls)
}

// Ping implements db.Conn.
func (f *FakeConn) Ping(ctx context.Context) error {
	f.mu.Lock()
	defer f.mu.Unlock()
	f.recordLocked("Ping")
	return f.checkLocked(ctx)
}

// ServerVersion implements db.Conn.
func (f *FakeConn) ServerVersion(ctx context.Context) (string, error) {
	f.mu.Lock()
	defer f.mu.Unlock()
	f.recordLocked("ServerVersion")
	if err := f.checkLocked(ctx); err != nil {
		return "", err
	}
	return f.version, nil
}

// ListSchemas implements db.Conn.
